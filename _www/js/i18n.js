let siteLang = SITE_DEFAULT_LANG;

function siteT(key) {
  const dict = SITE_I18N[siteLang] || SITE_I18N[SITE_DEFAULT_LANG];
  return dict[key] ?? SITE_I18N[SITE_DEFAULT_LANG][key] ?? key;
}

function getStoredLang() {
  try {
    const stored = localStorage.getItem("photodroid-lang");
    if (stored && SITE_I18N[stored]) return stored;
  } catch (_) {}
  return SITE_DEFAULT_LANG;
}

function applySiteI18n(lang) {
  siteLang = SITE_I18N[lang] ? lang : SITE_DEFAULT_LANG;
  document.documentElement.lang = siteLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = siteT(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = siteT(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", siteT(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", siteT(el.getAttribute("data-i18n-aria")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", siteT(el.getAttribute("data-i18n-title")));
  });

  const titleEl = document.querySelector("head title");
  if (titleEl) titleEl.textContent = siteT("meta.title");
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", siteT("meta.description"));
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.setAttribute("content", siteT("meta.title"));
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc) ogDesc.setAttribute("content", siteT("meta.description"));

  const diagTitle = document.getElementById("diag-title");
  const diagDesc = document.getElementById("diag-desc");
  if (diagTitle) diagTitle.textContent = siteT("arch.svgTitle");
  if (diagDesc) diagDesc.textContent = siteT("arch.svgDesc");

  const select = document.getElementById("site-lang");
  if (select) select.value = siteLang;

  document.dispatchEvent(new CustomEvent("site:lang", { detail: siteLang }));
}

function setSiteLang(lang) {
  const next = SITE_I18N[lang] ? lang : SITE_DEFAULT_LANG;
  try {
    localStorage.setItem("photodroid-lang", next);
  } catch (_) {}
  applySiteI18n(next);
}
